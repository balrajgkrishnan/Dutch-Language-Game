// Helper to normalize strings for comparisons
export function normalizeWord(str: string): string {
  return (str || '')
    .toLowerCase()
    .trim()
    .replace(/\s+/g, ' ')
    .replace(/[.,!?]+$/g, '');
}

// Fisher-Yates in-place shuffle helper
export function fisherYatesShuffle<T>(array: T[]): T[] {
  const result = [...array];
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

// Generate smart multiple choice options for imperfectum with Fisher-Yates
export function getImperfectumOptions(targetVerb: VerbItem, pool: VerbItem[], count: number = 4): string[] {
  const correct = targetVerb.imperfectum_ev;
  const sameTierPool = pool.filter(v => v.infinitief !== targetVerb.infinitief && v.tier === targetVerb.tier);
  const fallbackPool = pool.filter(v => v.infinitief !== targetVerb.infinitief);
  const source = sameTierPool.length >= count - 1 ? sameTierPool : fallbackPool;

  const shuffledSource = fisherYatesShuffle(source);
  const picked: string[] = [];
  const seen = new Set<string>([normalizeWord(correct)]);

  for (const v of shuffledSource) {
    const norm = normalizeWord(v.imperfectum_ev);
    if (!seen.has(norm)) {
      seen.add(norm);
      picked.push(v.imperfectum_ev);
      if (picked.length === count - 1) break;
    }
  }

  // Combine and perform thorough Fisher-Yates shuffle so correct answer is randomly positioned
  return fisherYatesShuffle([correct, ...picked]);
}

// Generate smart multiple choice options for voltooid deelwoord (Participle)
export function getParticipleOptions(targetVerb: VerbItem, pool: VerbItem[], count: number = 4): string[] {
  const correct = targetVerb.perfectum;
  const sameTierPool = pool.filter(v => v.infinitief !== targetVerb.infinitief && v.tier === targetVerb.tier);
  const fallbackPool = pool.filter(v => v.infinitief !== targetVerb.infinitief);
  const source = sameTierPool.length >= count - 1 ? sameTierPool : fallbackPool;

  const shuffledSource = fisherYatesShuffle(source);
  const picked: string[] = [];
  const seen = new Set<string>([normalizeWord(correct)]);

  for (const v of shuffledSource) {
    const norm = normalizeWord(v.perfectum);
    if (!seen.has(norm)) {
      seen.add(norm);
      picked.push(v.perfectum);
      if (picked.length === count - 1) break;
    }
  }

  return fisherYatesShuffle([correct, ...picked]);
}

// Check auxiliary verb
export function checkAux(picked: string, hulpwerkwoord: string): boolean {
  const allowed = hulpwerkwoord.split('/'); // ["heeft"], ["is"], or ["heeft", "is"]
  return allowed.includes(picked);
}

// Check participle
export function checkParticiple(typed: string, targetVerb: VerbItem): boolean {
  const t = normalizeWord(typed);
  const correct = normalizeWord(targetVerb.perfectum);
  if (t === correct) return true;
  if (targetVerb.accept_alt?.perfectum?.some(alt => normalizeWord(alt) === t)) return true;
  return false;
}

export const ZONE_SIZE = 20;

// Zones are derived, not stored: each tier's verbs are sorted alphabetically by
// infinitief and chunked into fixed-size zones. Tier population sizes (60/80/60
// once the full 200-verb roster is authored) must stay exact multiples of
// ZONE_SIZE for this to divide evenly — verified by the self-check in Task 6.
const TIER_ORDER: VerbItem['tier'][] = ['beginner', 'intermediate', 'advanced'];

function verbsForTier(tier: VerbItem['tier'], allVerbs: VerbItem[]): VerbItem[] {
  return allVerbs
    .filter(v => v.tier === tier)
    .sort((a, b) => a.infinitief.localeCompare(b.infinitief));
}

/** Zone index (0-9) a verb belongs to, given the full verb roster. */
export function getZoneIndex(verb: VerbItem, allVerbs: VerbItem[] = WERKWOORDEN_DATA): number {
  let zoneOffset = 0;
  for (const tier of TIER_ORDER) {
    const sameTier = verbsForTier(tier, allVerbs);
    if (tier === verb.tier) {
      const idxWithinTier = sameTier.findIndex(v => v.infinitief === verb.infinitief);
      return zoneOffset + Math.floor(idxWithinTier / ZONE_SIZE);
    }
    zoneOffset += Math.ceil(sameTier.length / ZONE_SIZE);
  }
  return -1; // verb.tier is 'expert' or unrecognized — not zoned
}

/** All verbs belonging to a given zone index (0-9), in stable alphabetical order. */
export function getVerbsInZone(zoneIndex: number, allVerbs: VerbItem[] = WERKWOORDEN_DATA): VerbItem[] {
  return allVerbs.filter(v => getZoneIndex(v, allVerbs) === zoneIndex);
}

/** Total number of zones present in the current roster. */
export function getTotalZoneCount(allVerbs: VerbItem[] = WERKWOORDEN_DATA): number {
  let count = 0;
  for (const tier of TIER_ORDER) {
    count += Math.ceil(verbsForTier(tier, allVerbs).length / ZONE_SIZE);
  }
  return count;
}

